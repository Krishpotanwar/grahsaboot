import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'

const HEADER = '// GENERATED by scripts/sync-evidence.ts from src/evidence. Do not edit.\n'
const out = 'supabase/functions/_shared/evidence'
// Read first and refuse on none: a wrong working directory must not wipe the generated folder and still "succeed".
const files = readdirSync('src/evidence').filter((n) => n.endsWith('.ts') && !n.endsWith('.test.ts'))
if (!files.length) {
  console.error(
    'sync-evidence: no .ts files in src/evidence. Run it from the repo root: npm run sync:evidence',
  )
  process.exit(1)
}
rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
for (const f of files) writeFileSync(`${out}/${f}`, HEADER + readFileSync(`src/evidence/${f}`, 'utf8'))
console.log('evidence synced')
