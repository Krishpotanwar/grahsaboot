import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterAll, describe, expect, it } from 'vitest'

const HEADER = '// GENERATED by scripts/sync-evidence.ts from src/evidence. Do not edit.\n'
const src = readdirSync('src/evidence').filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'))

describe('evidence core shared with Deno', () => {
  it('has an identical copy of every evidence module', () => {
    const shared = readdirSync('supabase/functions/_shared/evidence').sort()
    expect(shared).toEqual([...src].sort())
    for (const f of src)
      expect(readFileSync(`supabase/functions/_shared/evidence/${f}`, 'utf8'), f).toBe(
        HEADER + readFileSync(`src/evidence/${f}`, 'utf8'),
      )
  })

  it('holds no test file, and every copy starts with the header line', () => {
    const dir = 'supabase/functions/_shared/evidence'
    const files = readdirSync(dir)
    expect(files.filter((f) => f.endsWith('.test.ts'))).toEqual([])
    for (const f of files) expect(readFileSync(`${dir}/${f}`, 'utf8').startsWith(HEADER), f).toBe(true)
  })
})

describe('npm run sync:evidence', () => {
  const tmp = mkdtempSync(join(tmpdir(), 'gs-sync-'))
  afterAll(() => rmSync(tmp, { recursive: true, force: true }))

  const run = (cwd: string) =>
    spawnSync(
      process.execPath,
      [
        fileURLToPath(new URL('../../node_modules/tsx/dist/cli.mjs', import.meta.url)),
        fileURLToPath(new URL('../../scripts/sync-evidence.ts', import.meta.url)),
      ],
      { cwd, encoding: 'utf8', timeout: 20_000 },
    )

  it('refuses, and leaves the generated folder alone, when src/evidence has no .ts files or is missing', () => {
    const kept = join(tmp, 'supabase/functions/_shared/evidence/keep.ts')
    mkdirSync(join(tmp, 'src/evidence'), { recursive: true })
    mkdirSync(join(tmp, 'supabase/functions/_shared/evidence'), { recursive: true })
    writeFileSync(kept, '// kept\n')
    const empty = run(tmp)
    expect(empty.status).toBe(1)
    expect(empty.stdout).toBe('')
    expect(empty.stderr).toContain('no .ts files in src/evidence')
    expect(readFileSync(kept, 'utf8')).toBe('// kept\n')

    const elsewhere = mkdtempSync(join(tmp, 'cwd-'))
    expect(run(elsewhere).status).toBe(1)
    expect(readdirSync(elsewhere)).toEqual([])
  })
})
